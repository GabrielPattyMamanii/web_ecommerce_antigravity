// Prueba de paridad: el costo de una docena se calcula en DOS lugares y deben dar lo mismo.
//   - JavaScript: src/utils/costoDocena.js  (costo guardado en la venta, exportación y precios sugeridos)
//   - SQL:        calc_costo_docena_usd en supabase/migrations/20261024_backfill_costo_docena_usd.sql
//                 (backfill y botón "Recalcular costos")
// Corre la misma lista de casos por las dos y falla si alguna difiere. No toca ninguna base real: el SQL
// se ejecuta en un Postgres en memoria (PGlite).
//
// Uso:  npm run test:paridad        (si cambia la regla del costo, cambiar las dos y agregar el caso acá)

import { PGlite } from '@electric-sql/pglite';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { calcularCostoDocenaUsdDesdeFilas, calcularCostoParaPrecio } from '../src/utils/costoDocena.js';

const raiz = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migracion = (f) => fs.readFileSync(path.join(raiz, 'supabase', 'migrations', f), 'utf8').replace("NOTIFY pgrst, 'reload schema';", '');

// Cada caso es UNA boleta: sus filas y los bultos personalizados de la marca (0 = no tiene).
// `esperado` es el costo por docena de cada fila (null = sin costo), calculado a mano.
const fila = (codigo, docenas, precio, gastos, bultos) => ({ codigo, cantidad_docenas: docenas, precio_docena: precio, gastos, bultos });
const CASOS = [
    {
        nombre: 'bultos por fila (boleta 0080893)',
        personalizados: 0,
        filas: [fila('A', 48, 50, 180, 2), fila('B', 120, 40, 180, 7)],
        esperado: [(50 * 48 + 180 * 2) / 48, (40 * 120 + 180 * 7) / 120],
    },
    {
        nombre: 'personalizados, filas sin bultos: prorrateo (boleta 000491)',
        personalizados: 5,
        filas: [fila('A', 10, 68, 180, 0), fila('B', 20, 60, 180, 0)],
        esperado: [68 * (1 + (180 * 5) / (10 * 68 + 20 * 60)), 60 * (1 + (180 * 5) / (10 * 68 + 20 * 60))],
    },
    {
        nombre: 'personalizados Y bultos en las filas: gana bultos por fila',
        personalizados: 5,
        filas: [fila('A', 10, 68, 180, 2), fila('B', 20, 60, 180, 3)],
        esperado: [(68 * 10 + 180 * 2) / 10, (60 * 20 + 180 * 3) / 20],
    },
    {
        nombre: 'gastos pero ningún bulto (ni fila ni personalizado): sin costo',
        personalizados: 0,
        filas: [fila('A', 10, 68, 180, 0), fila('B', 20, 60, 180, 0)],
        esperado: [null, null],
    },
    {
        nombre: 'sin gastos y sin bultos: costo = precio',
        personalizados: 0,
        filas: [fila('A', 10, 68, 0, 0)],
        esperado: [68],
    },
    {
        nombre: 'boleta mixta: la fila con 0 bultos queda sin envío',
        personalizados: 0,
        filas: [fila('A', 10, 68, 180, 4), fila('B', 20, 60, 180, 0)],
        esperado: [(68 * 10 + 180 * 4) / 10, 60],
    },
    {
        nombre: 'personalizados pero la boleta no tiene valor de compra: sin costo',
        personalizados: 5,
        filas: [fila('A', 10, 0, 180, 0), fila('B', 20, 0, 180, 0)],
        esperado: [null, null],
    },
    {
        nombre: 'faltan datos de compra: sin costo',
        personalizados: 0,
        filas: [fila('A', 0, 68, 180, 1), fila('B', 20, null, 180, 1), fila('C', 5, 70, 180, 1)],
        esperado: [null, null, (70 * 5 + 180 * 1) / 5],
    },
    {
        nombre: 'gastos vacíos (NULL): se toman como 0',
        personalizados: 0,
        filas: [fila('A', 10, 68, null, 3)],
        esperado: [68],
    },
];

const db = new PGlite();
await db.exec(`
  CREATE TABLE public.tandas (id bigint generated by default as identity primary key, nombre text unique, parametros jsonb DEFAULT '{}');
  CREATE TABLE public.entradas (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), tanda_nombre text, marca text, marca_id text, codigo_boleta text, codigo text,
     cantidad_docenas numeric, precio_docena numeric, gastos numeric, bultos numeric);
  CREATE TABLE public.ventas (id bigint generated by default as identity primary key);
`);
await db.exec(migracion('20261023_ventas_costo_docena_usd.sql'));
await db.exec(migracion('20261024_backfill_costo_docena_usd.sql'));

const tolerancia = 1e-6;
const iguales = (a, b) => (a === null || b === null ? a === b : Math.abs(a - b) <= tolerancia);
let fallos = 0;
let comparaciones = 0;

for (const [i, caso] of CASOS.entries()) {
    const tanda = `TANDA ${i}`;
    const marcaId = `MARCA-${i}`;
    // Se alterna: la marca se identifica por marca_id (casos pares) o por su nombre (impares)
    const usaMarcaId = i % 2 === 0;
    const claveMarca = usaMarcaId ? marcaId : `MARCA ${i}`;
    if (caso.personalizados > 0) {
        await db.query('INSERT INTO tandas (nombre, parametros) VALUES ($1, $2)', [
            tanda, JSON.stringify({ marcasMetadata: { [claveMarca]: { bultos_personalizados: String(caso.personalizados) } } }),
        ]);
    }

    const filasDb = [];
    for (const f of caso.filas) {
        const r = await db.query(
            `INSERT INTO entradas (tanda_nombre, marca, marca_id, codigo_boleta, codigo, cantidad_docenas, precio_docena, gastos, bultos)
             VALUES ($1, $2, $3, $4, $5, $6, $7, $8, $9) RETURNING id`,
            [tanda, `MARCA ${i}`, usaMarcaId ? marcaId : null, `BOL-${i}`, f.codigo, f.cantidad_docenas, f.precio_docena, f.gastos, f.bultos],
        );
        filasDb.push({ ...f, id: r.rows[0].id });
    }

    for (const [j, f] of filasDb.entries()) {
        const resJs = calcularCostoDocenaUsdDesdeFilas(f, filasDb, caso.personalizados);
        const js = resJs.costo;
        // El SQL devuelve el costo y, si no se puede calcular, el código del motivo (el mismo que usa JS)
        const detalle = (await db.query('SELECT costo, codigo FROM public.calc_costo_docena_usd_detalle($1)', [f.id])).rows[0];
        const sqlRaw = detalle.costo;
        const sql = sqlRaw === null ? null : Number(sqlRaw);
        const sqlSimple = (await db.query('SELECT public.calc_costo_docena_usd($1) AS costo', [f.id])).rows[0].costo;
        const esperado = caso.esperado[j];
        // El precio sugerido usa el mismo costo; si el costo es null, cae a la fórmula por fila y avisa
        const precio = calcularCostoParaPrecio(f, filasDb, caso.personalizados);

        const problemas = [];
        if (!iguales(js, sql)) problemas.push(`JS (${js}) y SQL (${sql}) difieren`);
        if (!iguales(sqlSimple === null ? null : Number(sqlSimple), sql)) problemas.push('calc_costo_docena_usd y su versión con motivo difieren');
        if ((resJs.codigo ?? null) !== (detalle.codigo ?? null)) problemas.push(`motivo: JS (${resJs.codigo}) y SQL (${detalle.codigo}) difieren`);
        if (!iguales(js, esperado)) problemas.push(`JS (${js}) no coincide con lo esperado (${esperado})`);
        if (js !== null && !iguales(precio.costo, js)) problemas.push(`el precio sugerido (${precio.costo}) no usa el mismo costo (${js})`);
        if (js === null && precio.aviso === null) problemas.push('costo sin calcular pero el precio no trae aviso');
        comparaciones += 1;
        if (problemas.length > 0) {
            fallos += 1;
            console.log(`FALLA  ${caso.nombre} [fila ${f.codigo}]: ${problemas.join('; ')}`);
        }
    }
    console.log(`ok     ${caso.nombre}`);
}

await db.close();
console.log(`\n${comparaciones} comparaciones, ${fallos} con diferencias.`);
process.exit(fallos > 0 ? 1 : 0);
